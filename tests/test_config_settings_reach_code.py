# A workspace with the sections a real cluster run touches, written out rather
# than pointed at E:\ so the test runs anywhere.
WORKSPACE = {
    "io": {"result_dir": ".", "data_dir": "."},
    "instrument": {
        "telescope_focal_mm": 1048.0,
        "camera_pixel_um": 3.76,
        "binning": 1,
        "gain_e_per_adu": 0.689,
        "rdnoise_e": 2.1,
    },
    "photometry": {
        "apcorr": {"small_scale": 0.8, "large_scale": 2.4},
        "radii": {"sigma_clip": 3.0, "max_iter": 5},
    },
}


def _config_setting_every_mapped_key(key_map) -> dict:
    """A config that names every key the map knows, so nothing hides."""
    cfg = {"io": {"result_dir": ".", "data_dir": "."}}
    for row in key_map:
        path = tuple(row[0])
        node = cfg
        for part in path[:-1]:
            node = node.setdefault(part, {})
            if not isinstance(node, dict):
                break
        else:
            node.setdefault(path[-1], 1)
    return cfg


@pytest.fixture
def workspace(tmp_path):
    config = tmp_path / "apex_config.json"
    config.write_text(json.dumps(WORKSPACE), encoding="utf-8")
    return config


def test_the_instrument_geometry_arrives(workspace):
    """The pixel scale is derived from these two, so they have to be on `P`."""
    P = read_params(workspace).P
    assert P.telescope_focal_mm == pytest.approx(1048.0)
    assert P.camera_pixel_um == pytest.approx(3.76)


def test_the_pixel_scale_follows_the_configured_optics(workspace):
    """The defect itself: a non-default telescope must not land on the default
    plate scale. 206.265 * 3.76 / 1048 = 0.740 "/px, not 0.197."""
    from apex.core.instrument import InstrumentConfig

    params = read_params(workspace)
    assert InstrumentConfig(params).pix_scale_bin == pytest.approx(0.740, abs=1e-3)


def test_the_aperture_scales_arrive(workspace):
    P = read_params(workspace).P
    assert P.apcorr_small_scale == pytest.approx(0.8)
    assert P.apcorr_large_scale == pytest.approx(2.4)


def test_a_workspace_of_real_settings_loses_nothing(workspace):
    assert dropped_settings(read_params(workspace).P) == []


@pytest.mark.parametrize("mode,pinned", [("cmd", CMD_DROPPED), ("lc", LC_DROPPED)])
def test_the_set_of_settings_that_go_nowhere_is_the_pinned_one(mode, pinned, tmp_path):
    """Set every mapped key and check exactly which ones fail to arrive.

    A name appearing here that is not pinned is a new silent setting: add the
    keyword to the namespace constructor, or drop the key from the map if it is
    really dead — and either way say which in `docs/audit/CONFIG_REACHABILITY.md`.
    """
    if mode == "lc":
        from apex.config.parameters_lc import TOML_KEY_MAP, read_params as read
    else:
        from apex.config.parameters_cmd import TOML_KEY_MAP, read_params as read

    config = tmp_path / "apex_config.json"
    config.write_text(json.dumps(_config_setting_every_mapped_key(TOML_KEY_MAP)),
                      encoding="utf-8")
    lost = set(dropped_settings(read(config).P))
    assert not (lost - pinned), f"새로 사라지는 설정: {sorted(lost - pinned)}"
    assert not (pinned - lost), f"이제 도착한다 — 목록에서 지울 것: {sorted(pinned - lost)}"


def test_the_step7_cache_notices_an_aperture_change(tmp_path):
    """The signature listed `forced_r_ap_scale`, a name nothing set, so every
    run hashed None for it and a changed aperture reused the old cache."""
    import re
    from pathlib import Path

    source = (Path(__file__).absolute().parents[1]
              / "apex/gui/workflow/step7_forced_aperture_phot.py").read_text(encoding="utf-8")
    block = source[source.index("_FORCED_SIGNATURE_PARAMS = ("):]
    block = block[:block.index("\n)")]
    names = re.findall(r'"([a-z_0-9]+)"', block)
    assert "apcorr_small_scale" in names
    assert "apcorr_large_scale" in names
    assert "annulus_sigma_clip" in names
    assert "fitsky_max_iter" in names

    config = tmp_path / "apex_config.json"
    config.write_text(json.dumps(WORKSPACE), encoding="utf-8")
    P = read_params(config).P
    # `ref_cat_*` are defined in LC only; nothing sets them, so they cannot go
    # stale, but they are the remaining hole in this signature.
    absent = [n for n in names if not hasattr(P, n)]
    assert all(n.startswith("ref_cat_") for n in absent), absent


