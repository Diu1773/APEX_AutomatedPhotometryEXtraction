"""A setting written in a config file has to reach the code, or be listed here.

Three silent deaths, found 2026-08-16 by auditing a real workspace instead of
reading the loader:

    unmapped   the key is not in the key map, so it never enters `raw`
    dropped    it enters `raw` and the namespace constructor never names it, so
               `P` has no such attribute and every `getattr(P, name, default)`
               downstream takes the literal
    unread     it reaches `P` and no module reads it

`dropped` is the one that cost accuracy. `instrument.telescope_focal_mm` and
`camera_pixel_um` were mapped and never named, so `InstrumentConfig` fell back
to 3947 mm and 3.76 um — the CDK500 with a C3-61000 — for every instrument. The
five paper clusters *are* that instrument, so they were right by coincidence;
the QHY600 workspace would have run at 0.197 "/px instead of 0.740 and the
Sinistro at 0.197 instead of 0.389. Headless runs take `match.pixel_scale_arcsec`
straight from the file and were never affected, so no stored product is wrong —
only the GUI, which builds an `InstrumentConfig` and overwrote the correct value
with the default one.

The pinned lists below are not a target of zero. Most of what remains is
vestigial and removing it is its own job. They exist so the number cannot grow
without someone writing down why.
"""

